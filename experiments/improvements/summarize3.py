"""Scorecards for round 3 (written to ``results/round3/<stage>/scorecard.md``).

Cells are (class, block group). For each (mode, learner, design, workflow, calibration,
arm):

* ``coverage``: coverage of the 90 % interval pooled over cells;
* ``cov_err``: mean |coverage − 0.90| over cells, and ``worst``: the lowest cell;
* ``lr_rms``: RMS of log(estimated SD / true SD), the SD accuracy;
* ``rel_width``: mean interval half-width relative to ``current`` in the same workflow;
* ``rel_rmse``: RMSE of the arm's block estimates relative to the holdout map without
  recalibration (``holdout``/``raw``/``current``): the accuracy of the area estimate.
"""

from __future__ import annotations

import polars as pl

from experiments.improvements.round3 import RESULTS3

KEYS = ["mode", "learner", "design", "workflow", "calibration", "arm"]
CELL = [*KEYS, "class", "group"]


def load(stage: str, kind: str, suffix: str) -> pl.DataFrame:
    files = sorted((RESULTS3 / stage).glob(f"*_{kind}{suffix}.parquet"))
    return pl.concat(
        [pl.read_parquet(f).with_columns(pl.col("class").cast(pl.String)) for f in files],
        how="diagonal_relaxed",
    )


def cells(blocks: pl.DataFrame, reals: pl.DataFrame) -> pl.DataFrame:
    c = reals.group_by(CELL).agg(
        (pl.col("n_cov").sum() / pl.col("n_blocks").sum()).alias("coverage"),
        (pl.col("sum_log_ratio_sq").sum() / pl.col("n_blocks").sum()).sqrt().alias("lr_rms"),
        pl.col("n_blocks").sum().alias("n"),
    )
    b = blocks.group_by(CELL).agg(
        pl.col("width").mean(),
        pl.col("sd_true").mean().alias("rmse"),
        pl.col("ratio_rms").median().alias("ratio_med"),
    )
    out = (
        c.join(b, on=CELL, how="left", nulls_equal=True)
        .filter(pl.col("n") > 0)
        .with_columns(pl.col(pl.Float64).fill_nan(None))
    )
    cur = out.filter(pl.col("arm") == "current").select(
        [k for k in CELL if k != "arm"] + [pl.col("width").alias("w0")]
    )
    ref = out.filter(
        (pl.col("arm") == "current")
        & (pl.col("workflow") == "holdout")
        & (pl.col("calibration") == "raw")
    ).select(["mode", "learner", "design", "class", "group", pl.col("rmse").alias("r0")])
    return (
        out.join(cur, on=[k for k in CELL if k != "arm"], how="left", nulls_equal=True)
        .join(ref, on=["mode", "learner", "design", "class", "group"], how="left", nulls_equal=True)
        .with_columns(
            (pl.col("width") / pl.col("w0")).alias("rel_width"),
            (pl.col("rmse") / pl.col("r0")).alias("rel_rmse"),
        )
    )


def scorecard(cell: pl.DataFrame) -> pl.DataFrame:
    return cell.group_by(KEYS).agg(
        pl.col("coverage").mean(),
        (pl.col("coverage") - 0.9).abs().mean().alias("cov_err"),
        pl.col("coverage").min().alias("worst"),
        pl.col("lr_rms").mean(),
        pl.col("rel_width").mean(),
        pl.col("rel_rmse").mean(),
    )


def _table(df: pl.DataFrame) -> list[str]:
    def fmt(v: object) -> str:
        return f"{v:.3f}" if isinstance(v, float) else ("" if v is None else str(v))

    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.iter_rows()]
    return lines


def summarize_pipeline(quick: bool = False) -> None:
    suffix = "_quick" if quick else ""
    blocks = load("pipeline", "blocks", suffix)
    reals = load("pipeline", "realizations", suffix)
    cell = cells(blocks, reals)
    score = scorecard(cell)
    order = {"holdout": 0, "holdout_refit": 1, "cv": 2, "cv_nndm": 3}
    lines = [
        "# Round 3, Stage 1 (full pipelines): scorecard",
        "",
        "Generated by `experiments/improvements/summarize3.py`; definitions in its docstring.",
        "",
    ]
    for mode in ("continuous", "categorical"):
        sm = score.filter(pl.col("mode") == mode)
        if sm.height == 0:
            continue
        overall = (
            sm.group_by("workflow", "calibration", "arm")
            .agg(
                pl.col(c).mean() for c in ("coverage", "cov_err", "lr_rms", "rel_width", "rel_rmse")
            )
            .with_columns(pl.col("workflow").replace_strict(order, default=9).alias("_o"))
            .sort("_o", "calibration", "arm")
            .drop("_o")
        )
        lines += [f"## {mode}: mean over learners and designs", ""]
        lines += _table(overall.with_columns(pl.col(pl.Float64).round(3)))
        piv = (
            sm.with_columns(pl.format("{}:{}", "design", "learner").alias("dl"))
            .pivot(on="dl", index=["workflow", "calibration", "arm"], values="cov_err")
            .with_columns(pl.col("workflow").replace_strict(order, default=9).alias("_o"))
            .sort("_o", "calibration", "arm")
            .drop("_o")
        )
        lines += ["", f"### {mode}: coverage error by design and learner", ""]
        lines += _table(piv.with_columns(pl.col(pl.Float64).round(3)))
        worst = (
            sm.with_columns(pl.format("{}:{}", "design", "learner").alias("dl"))
            .pivot(on="dl", index=["workflow", "calibration", "arm"], values="worst")
            .with_columns(pl.col("workflow").replace_strict(order, default=9).alias("_o"))
            .sort("_o", "calibration", "arm")
            .drop("_o")
        )
        lines += ["", f"### {mode}: worst cell coverage by design and learner", ""]
        lines += _table(worst.with_columns(pl.col(pl.Float64).round(3)))
        lines += [""]
    rare = cell.filter(
        (pl.col("mode") == "categorical")
        & (pl.col("class") == "c")
        & pl.col("group").is_in(["tile_50", "domain"])
    )
    if rare.height:
        piv = (
            rare.with_columns(pl.format("{}:{}", "design", "learner").alias("dl"))
            .group_by("workflow", "calibration", "arm", "group")
            .agg(pl.col("coverage").mean(), pl.col("ratio_med").median())
            .with_columns(pl.col("workflow").replace_strict(order, default=9).alias("_o"))
            .sort("group", "_o", "calibration", "arm")
            .drop("_o")
        )
        lines += ["## Rare class (3 %) at large blocks: mean over learners and designs", ""]
        lines += _table(piv.with_columns(pl.col(pl.Float64).round(3)))
        lines += [""]
    diag_files = sorted((RESULTS3 / "pipeline").glob(f"*_diag{suffix}.parquet"))
    if diag_files:
        diag = pl.concat(
            [
                pl.read_parquet(f).with_columns(pl.lit(f.name.split("_diag")[0]).alias("cell"))
                for f in diag_files
            ],
            how="diagonal_relaxed",
        )
        choice = (
            diag.group_by("cell", "nndm_choice").len().sort("cell", "len", descending=[False, True])
        )
        lines += ["## Distance-matched folds chosen (count over realizations)", ""]
        lines += _table(choice)
        params = [c for c in diag.columns if c.endswith("_cal_param")]
        if params:
            lines += [
                "",
                "## Recalibration parameter (σ factor or temperature): median per cell",
                "",
            ]
            lines += _table(
                diag.group_by("cell")
                .agg(pl.col(params).median())
                .sort("cell")
                .with_columns(pl.col(pl.Float64).round(3))
            )
    out = RESULTS3 / "pipeline" / f"scorecard{suffix}.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())
